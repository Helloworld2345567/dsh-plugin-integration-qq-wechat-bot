#!/usr/bin/env node
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {manifestDigest,readSkillFiles} from './skill-contract.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const check=process.argv.includes('--check');
const {catalog,items}=await readSkillFiles(root);
const manifests=items.filter(item=>item.manifest).sort((a,b)=>a.skill.localeCompare(b.skill,'en')).map(item=>item.manifest);
const digest=await manifestDigest(root);
const manifestJson=JSON.stringify(manifests);
const descriptions=Object.fromEntries(items.map(item=>[item.skill,item.metadata.description]));
const entries=catalog.entries;
const tsCatalog=`// Generated by scripts/generate-skill-registry.mjs; do not edit.\nexport const PUBLISHED_SKILL_ENTRIES:Readonly<Record<string,string>>=Object.freeze(${JSON.stringify(entries)});\nexport const PUBLISHED_SKILL_DESCRIPTIONS:Readonly<Record<string,string>>=Object.freeze(${JSON.stringify(descriptions)});\n`;
const tsRegistry=`// Generated by scripts/generate-skill-registry.mjs; check:architecture rejects stale content.\nimport type {SkillOperationManifest} from './skill-operations.js';\nexport const PUBLISHED_SKILL_MANIFEST_DIGEST=${JSON.stringify(digest)};\nexport const PUBLISHED_SKILL_MANIFEST_JSON=${JSON.stringify(manifestJson)};\nfunction deepFreeze<T>(value:T):T{if(value&&typeof value==='object'){for(const child of Object.values(value as Record<string,unknown>))deepFreeze(child);Object.freeze(value);}return value;}\nexport const PUBLISHED_SKILL_OPERATIONS:readonly SkillOperationManifest[]=deepFreeze(JSON.parse(PUBLISHED_SKILL_MANIFEST_JSON) as SkillOperationManifest[]);\n`;
const pythonEntries=`# Generated by scripts/generate-skill-registry.mjs; do not edit.\nPUBLISHED_SKILL_ENTRIES = ${JSON.stringify(entries,null,4)}\n`;
// JSON.stringify emits valid Python syntax for this string-only map.
const outputs=new Map([
  ['src/core/published-skill-catalog.ts',tsCatalog],
  ['src/core/published-skill-operations.ts',tsRegistry],
  ['python/dsh_bot_runtime/skill_catalog.py',pythonEntries],
]);
for(const [relative,content] of outputs){
  const file=path.join(root,relative),current=await readFile(file,'utf8').catch(()=>undefined);
  if(check){if(current!==content)throw new Error(`SKILL_GENERATED_STALE:${relative}`);}
  else {await mkdir(path.dirname(file),{recursive:true});await writeFile(file,content,'utf8');}
}
if(check)console.log(JSON.stringify({status:'PASS',digest,skills:items.length,manifests:manifests.length}));
else console.log(JSON.stringify({status:'PASS',digest,generated:[...outputs.keys()]}));
