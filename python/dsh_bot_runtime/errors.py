_DYNAMIC_ERROR_CODES = (
    re.compile(r"PROVIDER_HTTP_[1-5][0-9]{2}"),
    re.compile(r"POST_HTTP_[1-5][0-9]{2}"),
    re.compile(r"GPT_SOVITS_(?:SET_SOVITS_WEIGHTS|SET_GPT_WEIGHTS|SET_REFER_AUDIO|TTS)_HTTP_[1-5][0-9]{2}"),
    re.compile(r"(?:AVIF|WEBP)_CODEC_UNAVAILABLE"),
)

def validated_error_code(code: object, fallback: str) -> str:
    """Accept only registered codes or bounded HTTP/codec templates."""
    if isinstance(code, str) and (code in PUBLIC_ERROR_CODES or any(pattern.fullmatch(code) for pattern in _DYNAMIC_ERROR_CODES)):
        return code
    return fallback

def public_error_code(error: BaseException, fallback: str) -> str:
    """Map an exception to a registered code without exposing message or type."""
    return validated_error_code(getattr(error, "code", None), fallback)
