import type {Context} from '@deepseek-ai/cordis';
import type {ModelSelectionRef} from '@deepseek-ai/dsh-agent';
import {boundContextSummary,createUserMessage} from '@deepseek-ai/dsh-llm';

/** Apply the frozen bot model after native Web selection without duplicating its notices. */
export function installBotModelSelection(ctx:Context,selection:ModelSelectionRef):()=>void {
  const registerNotice=()=>ctx.on('agent/pre-step',async({agent,messages,signal,step},next)=>{
    const result=await next();if(result.kind==='reject'||signal.aborted)return result;
    if(result.messages.length===0&&(step===1||messages.length>0))return result;
    const selected=selection.assembled,previous=agent.session.requestHeader()?.config;if(!selected)return result;
    const pending=result.messages.filter(message=>message.source?.kind!=='model-selection');
    if(previous&&(previous.provider!==selected.provider||previous.model!==selected.model)){
      const label=(model:{provider:string;model:string})=>previous.provider===selected.provider?model.model:`${model.provider}/${model.model}`;
      const from=label(previous),to=label(selected);
      pending.push(createUserMessage({content:[{type:'text',text:`[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`}],source:{kind:'model-selection',form:'notice',summary:boundContextSummary(`${from} → ${to}`)}}));
    }
    return {...result,messages:pending};
  },{prepend:true});
  let notice=registerNotice();
  const assembly=ctx.on('system-prompt/assemble',async(_assembly,_context,next)=>{
    const selected=selection.current,result=await next();selection.assembled=selected;
    // Web model selection can install its notice lazily, after the bot was initialized.
    notice();notice=registerNotice();
    return selected?{...result,variables:{...result.variables,provider:selected.provider,model:selected.model}}:result;
  },{prepend:true});
  const request=ctx.on('agent/request',async(_payload,next)=>{
    const result=await next(),selected=selection.assembled;if(!selected)return result;
    const {reasoningEffort:_inherited,...config}=result;
    return {...config,provider:selected.provider,model:selected.model,...selected.reasoningEffort===undefined?{}:{reasoningEffort:selected.reasoningEffort}};
  },{prepend:true});
  return()=>{assembly();request();notice();};
}
